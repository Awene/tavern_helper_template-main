import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import ts from 'typescript';
const file=new URL('../../../../SillyTavern-1.16.0/data/default-user/extensions/cultivation-rule-router/index.js',import.meta.url);
const source=fs.readFileSync(file,'utf8');
const ast=ts.createSourceFile('router.js',source,ts.ScriptTarget.Latest,true,ts.ScriptKind.JS);
const functions=new Map();
for(const n of ast.statements) if(ts.isFunctionDeclaration(n)) functions.set(n.name.text,n.getText(ast));
const data={enabled:true,api:{url:'local',model:'test',key:'SECRET'},filters:{book:{rule:{enabled:true}}},cacheSize:5};
const c={data,settings:()=>data,ctx:{extensionSettings:{cultivation_rule_router:data}},SETTINGS_KEY:'cultivation_rule_router',window:{CultivationRuleRouter:{}},CONFIG_EXPORT_VERSION:'0.8.0',clonePlain:x=>JSON.parse(JSON.stringify(x)),isSafeConfigKey:k=>!['__proto__','constructor','prototype'].includes(k),normalizeFilters:x=>x,routeCache:new Map(),persist(){},refreshOpenConfigFromSettings(){}};
vm.createContext(c);
vm.runInContext(['sanitizeConfigMetadata','exportRouterConfig','applyRouterConfig'].map(n=>functions.get(n)).join('\n'),c);
const start=source.indexOf('window.CultivationRuleRouter.getDiagnostics =');
const end=source.indexOf('function sanitizeConfigMetadata',start);
vm.runInContext(source.slice(start,end),c);
c.applyRouterConfig({__crr_export:true,filters:{book:{rule:{enabled:true}}},configMetadata:{book:{id:'bengexiuxian',version:'2026.10.22'}}});
assert.equal(c.exportRouterConfig({includeGlobal:false}).configMetadata.book.version,'2026.10.22');
assert.equal(c.window.CultivationRuleRouter.getDiagnostics().books.book.metadata.version,'2026.10.22');
assert.ok(!JSON.stringify(c.window.CultivationRuleRouter.getDiagnostics()).includes('SECRET'));
c.applyRouterConfig({__crr_export:true,filters:{book:{rule:{enabled:true}}}});
assert.equal(c.window.CultivationRuleRouter.getDiagnostics().books.book.metadata,null);
assert.equal(data.api.key,'SECRET');
console.log('PASS: router revision import/export, legacy import clears stale revision, diagnostics never expose credentials.');
