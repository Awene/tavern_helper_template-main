// ============ 故事查询 ============
export const findStory = (id: string | null): StoryOption | undefined =>
  id ? stories.find(s => s.id === id) : undefined;

export function resolveStorySettings(story: StoryOption, sel: Selection): StorySettings {
  return story.类型 === '通用' && findStory(story.id)
    ? { ...story.settings, 宗门: sel.门派归属 || '散修' }
    : story.settings;
}

// ============ 故事约束校验 / 描述 ============
export function isStoryAvailable(story: StoryOption, sel: Selection): boolean {
  if (!isLocationAvailable(sel.locationId, sel.种族) || !isSectAvailable(story.settings.宗门, sel.locationId))
    return false;
  if (story.settings.初始境界.大境界 !== '凡人' && (!sel.root.elements.length || sel.root.elements.includes('无')))
    return false;
  const c = story.constraints;
  if (!c) return true;

  // 出生地约束
  if (c.locationIds?.length) {
    if (!sel.locationId || !c.locationIds.includes(sel.locationId)) return false;
  }
  if (c.regionIds?.length) {
    if (!sel.locationId) return false;
    const path = findLocationPath(sel.locationId);
    if (!path.region || !c.regionIds.includes(path.region.id)) return false;
  }

  // 性别
  if (c.性别 && sel.性别 !== c.性别) return false;
  if (c.性别禁止?.includes(sel.性别)) return false;

  // 元阳/元阴
  if (c.元阳元阴必须 && !sel.元阳元阴) return false;
  if (typeof c.元阳元阴状态 === 'boolean' && sel.元阳元阴 !== c.元阳元阴状态) return false;

  // 种族 / 形态 / 剧本指定本体
  if (c.种族?.length && !c.种族.includes(sel.种族)) return false;
  if (c.必须人形 && findRace(sel.种族)?.canChooseTransformation && !sel.种族可化形) return false;
  if (c.种族细分必须为空 && sel.种族细分.trim()) return false;

  // 灵根五行
  if (c.灵根五行任意?.length) {
    if (!sel.root.elements.some(e => c.灵根五行任意!.includes(e))) return false;
  }
  if (c.灵根禁止?.length) {
    if (sel.root.elements.some(e => c.灵根禁止!.includes(e))) return false;
  }

  // 灵根品阶
  if (c.灵根品阶?.length) {
    const tier = rootTierLabel(sel.root);
    if (!c.灵根品阶.some(t => tier.includes(t))) return false;
  }

  // 体质等级
  if (c.physiqueTier?.length) {
    if (!c.physiqueTier.includes(sel.physique.tier)) return false;
  }

  // 门派归属
  if (c.门派归属?.length) {
    if (!c.门派归属.includes(sel.门派归属 ?? '')) return false;
  }

  return true;
}

/** 门派归属值 → 展示文本（''=无） */
function menpaiLabel(v: string): string {
  if (v === '') return '无';
  if (v === '散修') return '散修';
  return `${v}弟子`;
}

/** 列出当前选择下，故事约束未满足的具体原因；满足时返回空数组 */
export function whyStoryUnavailable(story: StoryOption, sel: Selection): string[] {
  const c = story.constraints;
  const reasons: string[] = [];
  if (story.settings.初始境界.大境界 !== '凡人' && (!sel.root.elements.length || sel.root.elements.includes('无')))
    reasons.push('修士开局须选择灵根');
  if (!isLocationAvailable(sel.locationId, sel.种族)) reasons.push('请先选择当前种族可用的出生地');
  if (!isSectAvailable(story.settings.宗门, sel.locationId)) reasons.push(`出生世界与${story.settings.宗门}不符`);
  if (!c) return reasons;

  if (c.locationIds?.length) {
    if (!sel.locationId || !c.locationIds.includes(sel.locationId)) {
      const names = c.locationIds.map(id => findLocation(id)?.name).filter(Boolean) as string[];
      reasons.push(`起始地点须为：${names.join(' / ')}`);
    }
  }
  if (c.regionIds?.length) {
    let ok = false;
    if (sel.locationId) {
      const path = findLocationPath(sel.locationId);
      if (path.region && c.regionIds.includes(path.region.id)) ok = true;
    }
    if (!ok) {
      const names = c.regionIds.map(id => findRegionById(id)?.name).filter(Boolean) as string[];
      reasons.push(`地域须为：${names.join(' / ')}`);
    }
  }
  if (c.性别 && sel.性别 !== c.性别) {
    reasons.push(`性别须为：${c.性别}`);
  }
  if (c.性别禁止?.includes(sel.性别)) {
    reasons.push(`性别不可为：${c.性别禁止.join(' / ')}`);
  }
  if (c.元阳元阴必须 && !sel.元阳元阴) {
    reasons.push(`须保持：${sel.性别 === '男' ? '元阳' : '元阴'}尚存`);
  }
  if (typeof c.元阳元阴状态 === 'boolean' && sel.元阳元阴 !== c.元阳元阴状态) {
    reasons.push(`${sel.性别 === '男' ? '元阳' : '元阴'}须为：${c.元阳元阴状态 ? '尚存' : '已损'}`);
  }
  if (c.种族?.length && !c.种族.includes(sel.种族)) {
    reasons.push(`种族须为：${c.种族.join(' / ')}`);
  }
  if (c.必须人形 && findRace(sel.种族)?.canChooseTransformation && !sel.种族可化形) {
    reasons.push('此开局要求主角以人形登场，请开启「可化形」');
  }
  if (c.种族细分必须为空 && sel.种族细分.trim()) {
    reasons.push(`种类须留空，由剧本决定${c.剧本指定种类 ? `为「${c.剧本指定种类}」` : ''}`);
  }
  if (c.灵根五行任意?.length) {
    if (!sel.root.elements.some(e => c.灵根五行任意!.includes(e))) {
      reasons.push(`灵根至少含：${c.灵根五行任意.join(' / ')}`);
    }
  }
  if (c.灵根禁止?.length) {
    const bad = sel.root.elements.filter(e => c.灵根禁止!.includes(e));
    if (bad.length) {
      reasons.push(`灵根不可含：${c.灵根禁止.join(' / ')}（当前含 ${bad.join('、')}）`);
    }
  }
  if (c.灵根品阶?.length) {
    const tier = rootTierLabel(sel.root);
    if (!c.灵根品阶.some(t => tier.includes(t))) {
      reasons.push(`灵根品阶须为：${c.灵根品阶.join(' / ')}（当前 ${tier}）`);
    }
  }
  if (c.physiqueTier?.length) {
    if (!c.physiqueTier.includes(sel.physique.tier)) {
      reasons.push(`体质须为：${c.physiqueTier.join(' / ')}（当前 ${sel.physique.tier}）`);
    }
  }
  if (c.门派归属?.length) {
    if (!c.门派归属.includes(sel.门派归属 ?? '')) {
      reasons.push(
        `门派归属须为：${c.门派归属.map(menpaiLabel).join(' / ')}（当前 ${menpaiLabel(sel.门派归属 ?? '')}）`,
      );
    }
  }
  return reasons;
}

export function describeConstraints(c?: StoryConstraints): string[] {
  if (!c) return [];
  const lines: string[] = [];
  if (c.locationIds?.length) {
    const names = c.locationIds.map(id => findLocation(id)?.name).filter(Boolean) as string[];
    if (names.length) lines.push(`出生地：${names.join(' / ')}`);
  }
  if (c.regionIds?.length) {
    const names = c.regionIds.map(id => findRegionById(id)?.name).filter(Boolean) as string[];
    if (names.length) lines.push(`地域：${names.join(' / ')}`);
  }
  if (c.性别) lines.push(`性别：${c.性别}`);
  if (c.性别禁止?.length) lines.push(`性别不可为：${c.性别禁止.join(' / ')}`);
  if (c.元阳元阴必须) lines.push('元阳/元阴：尚存');
  if (typeof c.元阳元阴状态 === 'boolean') lines.push(`元阳/元阴：${c.元阳元阴状态 ? '尚存' : '已损'}`);
  if (c.种族?.length) lines.push(`种族：${c.种族.join(' / ')}`);
  if (c.必须人形) lines.push('形态：必须为人形');
  if (c.种族细分必须为空) {
    lines.push(`种类：留空${c.剧本指定种类 ? `（由剧本指定为「${c.剧本指定种类}」）` : '（由剧本决定）'}`);
  }
  if (c.灵根五行任意?.length) lines.push(`灵根含：${c.灵根五行任意.join(' / ')}`);
  if (c.灵根品阶?.length) lines.push(`品阶：${c.灵根品阶.join(' / ')}`);
  if (c.灵根禁止?.length) lines.push(`不可：${c.灵根禁止.join(' / ')}`);
  if (c.physiqueTier?.length) lines.push(`体质：${c.physiqueTier.join(' / ')}`);
  if (c.门派归属?.length) lines.push(`门派：${c.门派归属.map(menpaiLabel).join(' / ')}`);
  return lines;
}

export function realmLabel(realm: StorySettings['初始境界']): string {
  return realm.大境界 === '凡人' ? '凡人' : `${realm.大境界}${realm.小境界 || '初期'}`;
}

export function describeSettings(s: StorySettings): string[] {
  const t = s.时间;
  return [
    `时间：${t.年}年 ${t.月}月 ${t.日}日${t.时辰 ? ' · ' + t.时辰 : ''}`,
    `宗门：${s.宗门}`,
    `初始境界：${realmLabel(s.初始境界)}`,
  ];
}

// ============ 自创剧本 ============
/**
 * 自创剧本按宗门分类；「特殊」分类不代表绑定剧情物品。
 */
export function deriveCustomStoryKind(sect: string): StoryKind {
  const s = (sect || '').trim();
  return !s || s === '散修' ? '通用' : '特殊';
}

export function emptyCustomStory(): CustomStory {
  return {
    id: '',
    name: '',
    desc: '',
    body: '',
    类型: '通用',
    settings: {
      时间: { 年: 7200, 月: 1, 日: 1, 时辰: '辰时' },
      宗门: '散修',
      初始境界: { 大境界: '炼气', 小境界: '初期' },
    },
  };
}

/** 自创剧本 → StoryOption（便于复用展示逻辑） */
export function customStoryToOption(c: CustomStory): StoryOption {
  return {
    id: c.id,
    name: c.name,
    desc: c.desc,
    body: c.body,
    cost: 0,
    glyph: '自',
    类型: deriveCustomStoryKind(c.settings.宗门),
    settings: c.settings,
    tags: ['自创'],
  };
}

/** 验证自创剧本最小可用条件 */
export function isCustomStoryValid(c: CustomStory): boolean {
  if (!c.name.trim()) return false;
  if (!c.body.trim()) return false;
  if (c.settings.时间.年 < 7000) return false;
  if (!c.settings.宗门.trim()) return false;
  if (!c.settings.初始境界.大境界.trim()) return false;
  return true;
}

